# 症状→疾病（反向推断）：触发词与其他类不同，需要单独处理
# 因为这类问句的主语是"症状"而非"疾病"，实体提取逻辑不同
_SYMPTOM_TO_DISEASE_KEYWORDS = [
    "可能是什么病", "是什么病引起", "可能得了", "可能是哪种病",
    "什么病会有", "什么原因导致",
]

# ──────────────────────────────────────────────────────
# 疾病/症状实体提取（保守策略：末尾/最长中文串）
# ──────────────────────────────────────────────────────

# 三种常见句式的正则模式：
#   "XXX的Y"       → 提取 X（"百日咳的并发症" → "百日咳"）
#   "XXX患者"      → 提取 X（"百日咳患者的血常规" → "百日咳"）
#   "XXX?"         → 提取 X（整句就是实体名）
_ENTITY_PATTERNS = [
    # 模式1：句首疾病名 + 助词/动词，如"百日咳的"、"糖尿病怎么"
    re.compile(r"^([一-龥A-Za-z0-9]{2,20}?)(?:的|有|是|会|怎|如何|吃|用|挂|治|预防|护理|隔离|属于)"),
    # 模式2：疾病名 + "患者"，如"百日咳患者的"
    re.compile(r"([一-龥A-Za-z0-9]{2,20}?)患者"),
    # 模式3：整句就是疾病名（2-20字中文/字母/数字，后可跟问号）
    re.compile(r"^([一-龥A-Za-z0-9]{2,20})[?？]?$"),
]


def _extract_entity(query: str) -> Optional[str]:
    """
    从问句中提取疾病或症状实体（保守策略，宁可返回 None 也不错提取）。

    采用三种正则模式依次尝试匹配，取第一个成功匹配的结果。
    过滤掉明显不是疾病名的常见词（人称代词、疑问代词等）和过短的词。

    参数:
        query (str): 用户问题原文

    返回:
        str: 提取到的实体名称（2-20字）
        None: 无法提取到合法实体
    """
    # 预处理：去除首尾空白和常见句末标点
    q = query.strip().rstrip("？?。.！!")

    for pat in _ENTITY_PATTERNS:
        m = pat.search(q)
        if m:
            entity = m.group(1).strip()

            # 过滤黑名单词（人称代词、疑问代词，不可能是疾病名）
            if entity in {"什么", "怎么", "如何", "为什么", "哪个", "哪种",
                          "这个", "那个", "我", "你", "他"}:
                continue  # 跳过，尝试下一个模式

            if len(entity) < 2:
                continue  # 太短（1字）不可靠，跳过

            return entity  # 返回第一个有效提取结果

    return None  # 所有模式都未能提取到合法实体


# ──────────────────────────────────────────────────────
# 主入口
# ──────────────────────────────────────────────────────

def classify(query: str) -> Optional[Tuple[str, str]]:
    """
    尝试用规则识别意图和实体，高置信度时返回结果，否则返回 None 让 LLM 兜底。

    规则命中条件（同时满足才算 high-confidence）：
      1. query 命中某个意图的关键词（且只命中一种，防歧义）
      2. 能提取到 2-20 字的中文实体
      3. 意图和实体不冲突（如 symptom_to_disease 的实体应是症状）

    参数:
        query (str): 用户问题原文

    返回:
        tuple(intent, entity): 成功识别时返回意图和实体
        None: 无法高置信度识别时返回（触发 LLM 兜底）
    """
    # 过滤边界情况：空字符串或超长查询直接放弃
    if not query or len(query) > 200:
        return None

    q_lower = query  # 中文不需要 lower()，直接用原文比对

    # ── 症状→疾病：反向推断，优先检查（因为触发词与其他意图不冲突）──
    for kw in _SYMPTOM_TO_DISEASE_KEYWORDS:
        if kw in q_lower:
            entity = _extract_entity(query)
            if entity:
                return ("symptom_to_disease", entity)
            return None  # 触发词命中但无法提取实体，交给 LLM

    # ── 其他 11 种意图：逐意图扫描关键词 ──
    matched_intent = None
    for intent, keywords in _INTENT_KEYWORDS.items():
        for kw in keywords:
            if kw in q_lower:
                if matched_intent is None:
                    matched_intent = intent  # 第一次命中，记录意图
                else:
                    # 出现第二个意图命中 → 歧义，降级到 LLM（宁缺毋滥）
                    return None
                break  # 同一意图内不需要继续扫描关键词

    if matched_intent is None:
        return None  # 没有任何意图命中，交给 LLM

    # ── 尝试提取实体 ──
    entity = _extract_entity(query)
    if not entity:
        return None  # 意图命中但无法提取实体，交给 LLM

    return (matched_intent, entity)  # 高置信度命中，返回 (意图, 实体)
