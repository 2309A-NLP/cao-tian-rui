"""
规则意图分类器 —— 只在**高置信度**场景下命中，其余交给 LLM 兜底。

设计原则（质量优先）：
1. 规则只识别**明确无歧义**的关键词组合，宁可不命中也不错分类
2. 需同时命中"疾病/症状触发词"+"意图触发词"才算 high confidence
3. 命中失败 → 返回 None → 上层 fallback 到 LLM Function Calling
4. 实体抽取采用"末尾疾病名""的前疾病名""开头疾病名"三种模式，取最长有效串

命中率目标：50-60% 的常见问题走规则（0ms），剩余走 LLM（1-3s）
"""

import re                                # 标准库：正则表达式，用于实体抽取
from typing import Optional, Tuple       # 标准库：类型注解，明确函数签名

# ──────────────────────────────────────────────────────
# 意图关键词表（同一意图内任一关键词命中即匹配）
