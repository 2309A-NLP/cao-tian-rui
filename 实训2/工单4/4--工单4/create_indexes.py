# -*- coding: utf-8 -*-
"""
一次性为数据库添加索引，大幅加速 JOIN 查询
运行一次即可，之后正常用 batch_process.py
"""
import sys, sqlite3, time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent / "src"))
from config import DB_PATH

print(f"数据库路径: {DB_PATH}")
print("正在添加索引（需要几分钟，请耐心等待）...\n")

# 用读写模式打开（不加 mode=ro）
conn = sqlite3.connect(str(DB_PATH))

indexes = [
    # A股票日行情表 - 最常用
    ("idx_a股行情_股票代码", '"A股票日行情表"', '"股票代码"'),
    ("idx_a股行情_交易日",   '"A股票日行情表"', '"交易日"'),
    ("idx_a股行情_代码日期", '"A股票日行情表"', '"股票代码", "交易日"'),

    # A股公司行业划分表
    ("idx_行业_股票代码",   '"A股公司行业划分表"', '"股票代码"'),
    ("idx_行业_交易日期",   '"A股公司行业划分表"', '"交易日期"'),
    ("idx_行业_代码日期",   '"A股公司行业划分表"', '"股票代码", "交易日期"'),
    ("idx_行业_一级行业",   '"A股公司行业划分表"', '"一级行业名称"'),
    ("idx_行业_标准",       '"A股公司行业划分表"', '"行业划分标准"'),

    # 基金债券持仓明细
    ("idx_债券持仓_基金代码", '"基金债券持仓明细"', '"基金代码"'),
    ("idx_债券持仓_日期",     '"基金债券持仓明细"', '"持仓日期"'),
    ("idx_债券持仓_第N大",    '"基金债券持仓明细"', '"第N大重仓股"'),

    # 基金股票持仓明细
    ("idx_股票持仓_基金代码", '"基金股票持仓明细"', '"基金代码"'),
    ("idx_股票持仓_日期",     '"基金股票持仓明细"', '"持仓日期"'),

    # 基金基本信息
    ("idx_基金基本_代码",   '"基金基本信息"', '"基金代码"'),
    ("idx_基金基本_简称",   '"基金基本信息"', '"基金简称"'),
    ("idx_基金基本_管理人", '"基金基本信息"', '"管理人"'),

    # 基金日行情表
    ("idx_基金行情_代码", '"基金日行情表"', '"基金代码"'),
    ("idx_基金行情_日期", '"基金日行情表"', '"交易日期"'),

    # 港股票日行情表
    ("idx_港股行情_代码", '"港股票日行情表"', '"股票代码"'),
    ("idx_港股行情_日期", '"港股票日行情表"', '"交易日"'),

    # 基金可转债持仓明细（之前遗漏，导致3表JOIN超时）
    ("idx_可转债_基金代码",   '"基金可转债持仓明细"', '"基金代码"'),
    ("idx_可转债_持仓日期",   '"基金可转债持仓明细"', '"持仓日期"'),
    ("idx_可转债_股票代码",   '"基金可转债持仓明细"', '"对应股票代码"'),
    ("idx_可转债_代码日期",   '"基金可转债持仓明细"', '"基金代码", "持仓日期"'),

    # 基金规模变动表
    ("idx_规模_基金代码", '"基金规模变动表"', '"基金代码"'),
    ("idx_规模_日期",     '"基金规模变动表"', '"截止日期"'),

    # 基金份额持有人结构
    ("idx_持有人_基金代码", '"基金份额持有人结构"', '"基金代码"'),
    ("idx_持有人_年度",     '"基金份额持有人结构"', '"定期报告所属年度"'),
]

for idx_name, table, cols in indexes:
    sql = f'CREATE INDEX IF NOT EXISTS {idx_name} ON {table}({cols})'
    t0 = time.time()
    try:
        conn.execute(sql)
        conn.commit()
        print(f"  ✓ {idx_name}  ({time.time()-t0:.1f}s)")
    except Exception as e:
        print(f"  ✗ {idx_name}: {e}")

conn.close()
print("\n全部索引创建完成！现在可以运行 batch_process.py 了。")
